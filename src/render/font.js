export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const FONT_COLS = 16;
export const FONT_ROWS = 6;
export const CELL = 8;
export const FONT_TEX = CELL * FONT_COLS;   // 128 x 48 rounded to 128

const ORDER = [];
for (let i = 32; i < 32 + FONT_COLS * FONT_ROWS; i++) ORDER.push(String.fromCharCode(i));

export function charCell(ch) {
  const c = ch.toUpperCase();
  const i = ORDER.indexOf(c);
  return i < 0 ? ORDER.indexOf('?') : i;
}

/** Build the font atlas as RGBA (white ink, alpha mask). */
export function buildFontTexture() {
  const w = CELL * FONT_COLS, h = CELL * FONT_ROWS;
  const data = new Uint8Array(w * h * 4);
  for (let i = 0; i < ORDER.length; i++) {
    const ch = ORDER[i];
    const rows = (G[ch] || G['?']).split('/');
    const cx = (i % FONT_COLS) * CELL;
    const cy = Math.floor(i / FONT_COLS) * CELL;
    for (let y = 0; y < GLYPH_H && y < rows.length; y++) {
      const row = rows[y];
      for (let x = 0; x < GLYPH_W && x < row.length; x++) {
        if (row[x] !== '#') continue;
        const px = cx + x, py = cy + y;
        const o = (py * w + px) * 4;
        data[o] = 255; data[o + 1] = 255; data[o + 2] = 255; data[o + 3] = 255;
      }
    }
  }
  return { data, width: w, height: h };
}
